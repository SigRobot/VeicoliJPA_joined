
    create table alimentazione (
        id integer generated by default as identity,
        descrizione varchar(30) not null unique,
        primary key (id)
    );

    create table bici (
        id integer not null,
        marce integer,
        pieghevole boolean,
        freno varchar(20) check ((freno in ('DISCO','TAMBURO','PATTINO'))),
        sospensione varchar(20) check ((sospensione in ('NESSUNA','ANTERIORE','FULL'))),
        primary key (id)
    );

    create table categoria (
        id integer generated by default as identity,
        descrizione varchar(50) not null unique,
        primary key (id)
    );

    create table colore (
        id integer generated by default as identity,
        descrizione varchar(30) not null unique,
        primary key (id)
    );

    create table macchina (
        id integer not null,
        porte integer not null,
        targa varchar(10) not null unique,
        primary key (id)
    );

    create table marca (
        id integer generated by default as identity,
        descrizione varchar(50) not null unique,
        primary key (id)
    );

    create table messaggi_sistema (
        lang varchar(4) not null,
        code varchar(30) not null,
        messaggio varchar(255),
        primary key (lang, code)
    );

    create table moto (
        id integer not null,
        targa varchar(10) not null unique,
        tipo_forcella varchar(20) check ((tipo_forcella in ('TELESCOPICA','UPSIDE_DOWN','RIGIDA'))),
        primary key (id)
    );

    create table veicolo (
        alimentazione_id integer not null,
        anno integer,
        categoria_id integer not null,
        colore_id integer,
        id integer generated by default as identity,
        marca_id integer not null,
        ruote integer not null,
        tipo_veicolo varchar(31) not null check ((tipo_veicolo in ('Veicolo','bici','macchina','moto'))),
        modello varchar(50) not null,
        primary key (id)
    );

